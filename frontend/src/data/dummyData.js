// Local prediction fallback — uses category, storage, and usage frequency
export function localPredictRisk(data) {
  const daysToExpiry = Number(data.days_to_expiry) || 7;
  const category = data.category || 'Other';

  // Shelf life based on category
  const shelfLife = CATEGORY_SHELF_LIFE[category] ?? 7;

  // Expiry ratio: how much of shelf life is left (0 = expired, 1 = just bought)
  const expiryRatio = Math.max(0, daysToExpiry / shelfLife);

  // Base score from expiry ratio (0 ratio = 100 score, 1+ ratio = near 0)
  let baseScore = Math.max(0, 100 - expiryRatio * 60);

  // Storage multiplier
  const storageMultiplier =
    data.storage_type === 'Frozen' ? 0.5
    : data.storage_type === 'Room Temperature' ? 1.4
    : 1.0; // Refrigerated

  // Usage frequency multiplier
  const usageMultiplier =
    data.usage_frequency === 'rarely' ? 1.25
    : data.usage_frequency === 'often' ? 0.75
    : 1.0; // normal

  // Category inherent risk (perishable categories get a bump)
  const categoryRiskBonus =
    category === 'Seafood' ? 15
    : category === 'Meat' ? 10
    : category === 'Vegetable' ? 5
    : category === 'Fruit' ? 3
    : 0;

  let score = Math.min(100, Math.round(baseScore * storageMultiplier * usageMultiplier + categoryRiskBonus));
  score = Math.max(0, score);

  let risk_label, explanation, suggested_action;
  const catActions = CATEGORY_ACTIONS[category];

  if (score >= 70) {
    risk_label = 'High Risk';
    explanation = `${data.food_name || 'Makanan ini'} (${category}) memiliki risiko tinggi terbuang. Dengan sisa ${daysToExpiry} hari dari estimasi shelf life ${shelfLife} hari untuk kategori ${category}, dan disimpan di ${data.storage_type}, makanan ini perlu segera ditangani.`;
    suggested_action = catActions?.high ?? 'Segera gunakan hari ini, masak menjadi resep, atau donasikan jika berlebih.';
  } else if (score >= 40) {
    risk_label = 'Warning';
    explanation = `${data.food_name || 'Makanan ini'} (${category}) memiliki risiko sedang. Sisa ${daysToExpiry} hari dari shelf life normal ${shelfLife} hari untuk ${category}. Penyimpanan ${data.storage_type} ${data.storage_type === 'Frozen' ? 'membantu memperlambat kerusakan' : data.storage_type === 'Room Temperature' ? 'mempercepat penurunan kualitas' : 'cukup baik'}.`;
    suggested_action = catActions?.warning ?? 'Rencanakan penggunaan dalam 1-2 hari ke depan. Pertimbangkan untuk memasak atau jual di marketplace.';
  } else {
    risk_label = 'Safe';
    explanation = `${data.food_name || 'Makanan ini'} (${category}) masih dalam kondisi aman. Sisa ${daysToExpiry} hari masih cukup jauh dari batas shelf life ${shelfLife} hari untuk kategori ${category}.`;
    suggested_action = catActions?.safe ?? 'Simpan dengan benar dan pantau secara berkala.';
  }

  return {
    risk_score: score,
    risk_label,
    explanation,
    suggested_action,
    food_name: data.food_name,
    days_to_expiry: daysToExpiry,
  };
}

