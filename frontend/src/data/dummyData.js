const today = new Date();
const dayMs = 86400000;

function daysFromNow(days) {
  return new Date(today.getTime() + days * dayMs).toISOString().slice(0, 10);
}

function daysAgo(days) {
  return new Date(today.getTime() - days * dayMs).toISOString().slice(0, 10);
}

function getRiskLevel(daysToExpiry) {
  if (daysToExpiry <= 1) return 'High Risk';
  if (daysToExpiry <= 3) return 'Warning';
  return 'Safe';
}

function getRiskScore(daysToExpiry) {
  if (daysToExpiry <= 0) return 95;
  if (daysToExpiry <= 1) return 85;
  if (daysToExpiry <= 2) return 70;
  if (daysToExpiry <= 3) return 55;
  if (daysToExpiry <= 5) return 35;
  return 15;
}

